"use client";
import * as React from "react";
import { Trash2 } from "lucide-react";
import { Table, TableHeader, TableBody, TableHeadCell } from "@/components/ui/Table";
import { BulkActionBar } from "@/components/ui/BulkActionBar";
import { ColumnsVisibilityDropdown } from "@/components/ui/ColumnsVisibilityDropdown";
import { BarcodesManager } from "@/hooks/barcode_hooks/useBarcodesManager";
import { BarcodesFilterBar } from "../shared/BarcodesFilterBar";
import { BarcodesEmptyState } from "../shared/BarcodesEmptyState";
import { GeneratedBarcodeRow } from "./GeneratedBarcodeRow";

interface GeneratedBarcodesTableProps {
    manager: BarcodesManager<"generated">;
}

const COLUMNS = [
    { key: "productName", label: "Product Name" },
    { key: "serialNumber", label: "Serial Number" },
    { key: "mrp", label: "MRP" },
    { key: "warehouse", label: "Warehouse" },
    { key: "generatedBy", label: "Generated By" },
    { key: "status", label: "Status" },
];

const DEFAULT_COLUMNS: Record<string, boolean> = Object.fromEntries(COLUMNS.map((column) => [column.key, true]));

/** Barcodes generated or printed but not received into stock yet. */
export function GeneratedBarcodesTable({ manager }: GeneratedBarcodesTableProps) {
    const { toggleSelection, openDrawer, handleDelete, canEditRecord, canDelete, sortKey, sortDirection, handleSort } = manager;
    const [visibleColumns, setVisibleColumns] = React.useState<Record<string, boolean>>(DEFAULT_COLUMNS);

    const handleToggleColumn = (key: string) => setVisibleColumns((prev) => ({ ...prev, [key]: !prev[key] }));
    const handleResetColumns = () => setVisibleColumns(DEFAULT_COLUMNS);

    const handleView = React.useCallback((id: string) => openDrawer("view-barcode", id), [openDrawer]);
    const handleEdit = React.useCallback((id: string) => openDrawer("edit-barcode", id), [openDrawer]);
    const handleDeleteOne = React.useCallback((id: string) => handleDelete([id]), [handleDelete]);

    return (
        <div className="flex flex-col w-full h-full relative bg-brand-bg/20">
            <div className="border-b border-brand-subtext/20 bg-white">
                <BarcodesFilterBar manager={manager} dateLabel="Created"
                    actions={
                        <ColumnsVisibilityDropdown
                            columns={COLUMNS}
                            visibleColumns={visibleColumns}
                            onToggleColumn={handleToggleColumn}
                            onReset={handleResetColumns}
                        />
                    }
                />
            </div>

            <div className="overflow-x-auto custom-scrollbar flex-1">
                {manager.activeTabData.length === 0 ? (
                    <BarcodesEmptyState title="No generated barcodes" subtitle="Generate barcodes from Create Barcode, or adjust your search and filters." />
                ) : (
                    <Table>
                        <TableHeader>
                            <TableHeadCell className="w-12 text-center">
                                <input
                                    type="checkbox"
                                    checked={manager.isAllSelected}
                                    onChange={() => toggleSelection("ALL")}
                                    className="h-4 w-4 rounded border-brand-subtext/30 text-emerald-600 focus:ring-emerald-500 cursor-pointer"
                                />
                            </TableHeadCell>
                            {visibleColumns.productName !== false && <TableHeadCell sortable activeDirection={sortKey === "productName" ? sortDirection : null} onClick={() => handleSort("productName")}>Product Name</TableHeadCell>}
                            {visibleColumns.serialNumber !== false && <TableHeadCell sortable activeDirection={sortKey === "serialNumber" ? sortDirection : null} onClick={() => handleSort("serialNumber")}>Serial Number</TableHeadCell>}
                            {visibleColumns.mrp !== false && <TableHeadCell sortable activeDirection={sortKey === "mrp" ? sortDirection : null} onClick={() => handleSort("mrp")}>MRP</TableHeadCell>}
                            {visibleColumns.warehouse !== false && <TableHeadCell sortable activeDirection={sortKey === "currentLocation" ? sortDirection : null} onClick={() => handleSort("currentLocation")}>Warehouse</TableHeadCell>}
                            {visibleColumns.generatedBy !== false && <TableHeadCell sortable activeDirection={sortKey === "createdBy" ? sortDirection : null} onClick={() => handleSort("createdBy")}>Generated By</TableHeadCell>}
                            {visibleColumns.status !== false && <TableHeadCell sortable activeDirection={sortKey === "status" ? sortDirection : null} onClick={() => handleSort("status")}>Status</TableHeadCell>}
                            <TableHeadCell className="text-right">Action</TableHeadCell>
                        </TableHeader>

                        <TableBody>
                            {manager.activeTabData.map((barcode) => (
                                <GeneratedBarcodeRow
                                    key={barcode.id}
                                    barcode={barcode}
                                    isSelected={manager.selectedIds.includes(barcode.id)}
                                    visibleColumns={visibleColumns}
                                    canEdit={canEditRecord(barcode)}
                                    canDelete={canDelete(barcode)}
                                    onToggleSelect={toggleSelection}
                                    onView={handleView}
                                    onEdit={handleEdit}
                                    onDelete={handleDeleteOne}
                                />
                            ))}
                        </TableBody>
                    </Table>
                )}
            </div>

            <BulkActionBar selectedCount={manager.selectedIds.length} onClearSelection={manager.clearSelection}>
                <button
                    onClick={manager.handleBulkDelete}
                    className="flex items-center gap-2 rounded-lg px-3 py-1.5 text-sm font-medium text-red-400 transition-colors hover:bg-white/10 hover:text-red-300"
                >
                    <Trash2 className="h-4 w-4" />
                    <span className="hidden sm:inline">Delete Selected</span>
                </button>
            </BulkActionBar>
        </div>
    );
}
