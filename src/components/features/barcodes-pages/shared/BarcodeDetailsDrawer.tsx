"use client";
import * as React from "react";
import Image from "next/image";
import { Box, Clock, Hash, Tag, Truck, User, UserRound } from "lucide-react";
import { Drawer } from "@/components/ui/Drawer";
import { useRetainedValue } from "@/hooks/products_hooks/useRetainedValue";
import { BarcodesManager } from "@/hooks/barcode_hooks/useBarcodesManager";
import { BarcodesTabKey } from "@/types/barcodes";
import { formatBarcodeDateTime, formatBarcodeMoney } from "@/utils/barcodeRules";
import { BarcodeStatusBadge } from "./BarcodeStatusBadge";
import { BarcodeLifecycleTimeline } from "./BarcodeLifecycleTimeline";

type DetailsManager = Pick<BarcodesManager<BarcodesTabKey>, "drawerMode" | "activeBarcode" | "activeJourney" | "closeDrawer">;

interface BarcodeDetailsDrawerProps {
    manager: DetailsManager;
}

function InfoTile({ icon: Icon, label, value, mono = false }: { icon: React.ComponentType<{ className?: string }>; label: string; value: string; mono?: boolean }) {
    return (
        <div className="rounded-lg border border-brand-subtext/15 bg-brand-bg/30 p-4 flex items-start gap-3">
            <Icon className="h-5 w-5 text-brand-subtext mt-0.5 shrink-0" />
            <div className="flex min-w-0 flex-col">
                <span className="text-xs font-semibold text-brand-subtext">{label}</span>
                <span className={`text-sm font-bold text-brand-text mt-0.5 break-words ${mono ? "font-mono" : ""}`}>{value}</span>
            </div>
        </div>
    );
}

/** Read-only barcode identity and its full journey. Shared by List, Generate and History. */
export function BarcodeDetailsDrawer({ manager }: BarcodeDetailsDrawerProps) {
    const isOpen = manager.drawerMode === "view-barcode" && manager.activeBarcode !== null;
    // Keep the record and its journey on screen while the drawer slides out.
    const barcode = useRetainedValue(manager.activeBarcode, isOpen);
    const journey = useRetainedValue(manager.activeJourney, isOpen);

    return (
        <Drawer
            title="Barcode Details"
            isOpen={isOpen}
            onClose={manager.closeDrawer}
            width="w-full sm:w-[calc(100vw-260px)]"
        >
            {barcode && (
                <div className="mx-auto flex max-w-3xl flex-col gap-4 pb-32">
                    <div className="rounded-xl border border-brand-subtext/20 bg-white p-6 shadow-sm flex flex-col md:flex-row items-center gap-4">
                        <div className="relative h-32 w-32 shrink-0 overflow-hidden rounded-xl border border-brand-subtext/15 bg-brand-bg/30">
                            {barcode.image && <Image src={barcode.image} alt={barcode.productName} fill sizes="128px" className="object-contain p-4" />}
                        </div>
                        <div className="flex flex-col gap-2 text-center md:text-left">
                            <h3 className="text-xl font-bold text-brand-text">{barcode.productName}</h3>
                            <div className="flex flex-wrap items-center justify-center gap-2 md:justify-start">
                                <span className="inline-block rounded-full bg-emerald-100 px-3 py-1 text-xs font-bold text-emerald-700 w-max">
                                    Variant: {barcode.variant}
                                </span>
                                <BarcodeStatusBadge status={barcode.status} />
                            </div>
                            <p className="text-sm font-mono text-brand-subtext mt-2 break-all">Serial: {barcode.serialNumber}</p>
                        </div>
                    </div>

                    <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
                        <InfoTile icon={Tag} label="MRP" value={formatBarcodeMoney(barcode.mrp)} />
                        <InfoTile icon={Box} label="Current Location" value={barcode.currentLocation} />
                        <InfoTile icon={User} label="Generated By" value={barcode.createdBy} />
                        <InfoTile icon={Clock} label="Generated At" value={formatBarcodeDateTime(barcode.createdAt)} />
                        <InfoTile icon={Truck} label="Supplier" value={barcode.supplier?.name ?? "—"} />
                        <InfoTile icon={UserRound} label="Customer" value={barcode.customer?.name ?? "—"} />
                        <InfoTile icon={Hash} label="SKU" value={barcode.sku || "—"} mono />
                        <InfoTile
                            icon={Clock}
                            label="Last Edited"
                            value={barcode.updatedAt ? `${formatBarcodeDateTime(barcode.updatedAt)} · ${barcode.updatedBy ?? "—"}` : "—"}
                        />
                    </div>

                    <div className="flex flex-col gap-3">
                        <h4 className="text-sm font-bold text-brand-text">Barcode Journey</h4>
                        <BarcodeLifecycleTimeline entries={journey} />
                    </div>
                </div>
            )}
        </Drawer>
    );
}
