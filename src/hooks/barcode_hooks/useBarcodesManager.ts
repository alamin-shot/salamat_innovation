// LAYER 3: Single orchestration hook for Barcode List, Generate Barcode and
// Barcode History. Each route passes its own tab key.
// Pipeline: Search -> Filters -> Date range -> Sort -> Paginate.
// Search, filters, date range and page live in the URL.

// ── Per-tab wiring ──────────────────────────────────────────────────────────
type RowSourceMap = { [P in BarcodesTabKey]: (barcodes: Barcode[], history: BarcodeHistoryRow[]) => BarcodesRecordMap[P][] };
type TextMap = { [P in BarcodesTabKey]: (row: BarcodesRecordMap[P]) => (string | null)[] };
type DateMap = { [P in BarcodesTabKey]: (row: BarcodesRecordMap[P]) => string };

const ROW_SOURCES: RowSourceMap = {
    list: (barcodes) => barcodes,
    generated: (barcodes) => barcodes.filter((barcode) => isPreReceipt(barcode.status)),
    history: (_, history) => history,
};

const SEARCH_TEXT: TextMap = {
    list: (row) => [row.serialNumber, row.productName, row.variant, row.sku],
    generated: (row) => [row.serialNumber, row.productName, row.variant, row.sku],
    history: (row) => [row.serialNumber, row.productName, row.variant, row.supplier, row.customer, row.reference],
};

/** List / Generate filter on the created date; History on the event date. */
const DATE_OF: DateMap = {
    list: (row) => row.createdAt,
    generated: (row) => row.createdAt,
    history: (row) => row.timestamp,
};

// ── Filter dropdowns per tab ────────────────────────────────────────────────
interface FilterDef<T> {
    key: BarcodeFilterKey;
    label: string;
    /** The value a row is matched on; never "" (that means "All"). */
    getValue: (row: T) => string;
    options?: BarcodeFilterOption[];
    /** true: only `options` are offered, and unknown URL values are ignored. */
    closed?: boolean;
}
type FilterDefMap = { [P in BarcodesTabKey]: FilterDef<BarcodesRecordMap[P]>[] };

/** Stands in for an empty party so it never collides with "All" (""). */
const NONE_VALUE = "__none__";
const orNone = (value: string | null): string => (value && value.trim() ? value.trim() : NONE_VALUE);
const toOptions = (values: readonly string[]): BarcodeFilterOption[] => values.map((value) => ({ label: value, value }));

const locationFilter = <T>(getValue: (row: T) => string): FilterDef<T> => ({
    key: "location",
    label: "Location",
    getValue,
    options: toOptions(BARCODE_LOCATIONS),
    closed: true,
});

const FILTER_DEFS: FilterDefMap = {
    list: [
        { key: "status", label: "Status", getValue: (row) => row.status, options: toOptions(BARCODE_EVENT_TYPES), closed: true },
        locationFilter((row) => row.currentLocation),
        { key: "supplier", label: "Supplier", getValue: (row) => orNone(row.supplier?.name ?? null) },
        { key: "customer", label: "Customer", getValue: (row) => orNone(row.customer?.name ?? null) },
    ],
    generated: [
        { key: "status", label: "Status", getValue: (row) => row.status, options: toOptions(BARCODE_PRE_RECEIPT_STATUSES), closed: true },
        locationFilter((row) => row.currentLocation),
        { key: "generatedBy", label: "Generated By", getValue: (row) => orNone(row.createdBy) },
    ],
    history: [
        { key: "eventType", label: "Event Type", getValue: (row) => row.eventType, options: toOptions(BARCODE_EVENT_TYPES), closed: true },
        locationFilter((row) => row.location),
        { key: "supplier", label: "Supplier", getValue: (row) => orNone(row.supplier) },
        { key: "customer", label: "Customer", getValue: (row) => orNone(row.customer) },
    ],
};

function buildFilterOptions<T>(def: FilterDef<T>, rows: T[], selected: string | undefined): BarcodeFilterOption[] {
    const options = [...(def.options ?? [])];
    const known = new Set(options.map((option) => option.value));

    if (!def.closed) {
        Array.from(new Set(rows.map(def.getValue)))
            .filter((value) => !known.has(value))
            .sort((a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: "base" }))
            .forEach((value) => {
                known.add(value);
                options.push({ label: value === NONE_VALUE ? "None" : value, value });
            });
    }

    // Keep the active choice listed after its last record is gone, so it stays visible and clearable.
    if (selected && !known.has(selected)) {
        options.push({ label: selected === NONE_VALUE ? "None" : selected, value: selected });
    }
    return options;
}

// ── URL helpers ─────────────────────────────────────────────────────────────
const DATE_PARAMS = { from: "from", to: "to" } as const;

/** Every filter key any tab can write, so switching pages never leaves stale params. */
const ALL_FILTER_KEYS: BarcodeFilterKey[] = ["status", "eventType", "location", "supplier", "customer", "generatedBy"];

interface UrlView {
    search: string;
    page: number;
    filters: BarcodeFilterValues;
    dateRange: BarcodeDateRange;
}

function parsePage(value: string | null): number {
    const parsed = value ? parseInt(value, 10) : 1;
    return Number.isNaN(parsed) || parsed < 1 ? 1 : parsed;
}

/** Reads only this tab's filters; a closed filter ignores values it does not offer. */
function readUrlView<K extends BarcodesTabKey>(tab: K, params: URLSearchParams): UrlView {
    const filters: BarcodeFilterValues = {};
    FILTER_DEFS[tab].forEach((def) => {
        const value = params.get(def.key);
        if (!value) {
            return;
        }
        if (def.closed && !(def.options ?? []).some((option) => option.value === value)) {
            return;
        }
        filters[def.key] = value;
    });

    const from = parseDayKey(params.get(DATE_PARAMS.from));
    const to = parseDayKey(params.get(DATE_PARAMS.to));
    // A reversed range from a hand-edited URL is swapped rather than matching nothing.
    const dateRange: BarcodeDateRange = from && to && from > to ? { from: to, to: from } : { from, to };

    return {
        search: params.get("search") || "",
        page: parsePage(params.get("page")),
        filters,
        dateRange,
    };
}

function writeUrlView(params: URLSearchParams, view: UrlView): void {
    params.set("page", view.page.toString());
    const search = view.search.trim();
    if (search) {
        params.set("search", search);
    } else {
        params.delete("search");
    }
    ALL_FILTER_KEYS.forEach((key) => {
        const value = view.filters[key];
        if (value) {
            params.set(key, value);
        } else {
            params.delete(key);
        }
    });
    (["from", "to"] as const).forEach((end) => {
        const value = view.dateRange[end];
        if (value) {
            params.set(DATE_PARAMS[end], value);
        } else {
            params.delete(DATE_PARAMS[end]);
        }
    });
}

// ── Helpers ─────────────────────────────────────────────────────────────────
const getRowId = (row: BarcodesRow): string => row.id;

function toDrawerMode(value: string | null): BarcodesDrawerMode {
    return BARCODES_DRAWER_MODES.find((mode) => mode === value) ?? "none";
}

function compareValues(a: unknown, b: unknown): number {
    if (typeof a === "number" && typeof b === "number") {
        return a - b;
    }
    return String(a ?? "").localeCompare(String(b ?? ""), undefined, { numeric: true, sensitivity: "base" });
}

const isEditableTab = (tab: BarcodesTabKey): boolean => BARCODES_EDITABLE_TABS.some((item) => item === tab);

/** One toast per outcome, plus each rejection reason (first few only). */
function reportResult(result: BarcodeActionResult, success: (count: number) => string): void {
    if (result.applied.length > 0) {
        toast.success(success(result.applied.length));
    }
    result.rejected.slice(0, 3).forEach((rejection) => toast.error(rejection.reason));
    if (result.rejected.length > 3) {
        toast.error(`${result.rejected.length - 3} more record(s) were not changed.`);
    }
}

export function useBarcodesManager<K extends BarcodesTabKey>(tab: K) {
    const barcodes = useGlobalBarcodesStore((state) => state.barcodes);
    const command = useCommandParams();
    const pathname = usePathname();
    const searchParams = useSearchParams();
    const [isPending, startTransition] = useTransition();

    // History rows are only derived on the History page.
    const historyRows = useMemo(() => (tab === "history" ? buildHistoryRows(barcodes) : []), [tab, barcodes]);
    const rows: BarcodesRecordMap[K][] = useMemo(
        () => ROW_SOURCES[tab](barcodes, historyRows),
        [tab, barcodes, historyRows],
    );

    // ── View state (seeded from the URL) ────────────────────────────────────
    const [initialView] = useState(() => readUrlView(tab, new URLSearchParams(searchParams.toString())));
    const [searchQuery, setSearchQuery] = useState(initialView.search);
    const [debouncedQuery, setDebouncedQuery] = useState(initialView.search);
    const [filters, setFilters] = useState<BarcodeFilterValues>(initialView.filters);
    const [dateRange, setDateRangeState] = useState<BarcodeDateRange>(initialView.dateRange);
    const [currentPage, setCurrentPage] = useState(initialView.page);
    const [perPage, setPerPage] = useState(BARCODES_PER_PAGE);
    const [selectedIds, setSelectedIds] = useState<string[]>([]);
    const [sortKey, setSortKey] = useState<(keyof BarcodesRecordMap[K] & string) | null>(null);
    const [sortDirection, setSortDirection] = useState<BarcodesSortDirection>(null);
    const isFirstSearchEffect = useRef(true);

    // Debounced search, same timing as the other table managers.
    useEffect(() => {
        const timer = setTimeout(() => setDebouncedQuery(searchQuery), 300);
        return () => clearTimeout(timer);
    }, [searchQuery]);

    useEffect(() => {
        if (isFirstSearchEffect.current) {
            isFirstSearchEffect.current = false;
            return;
        }
        setCurrentPage(1);
        setSelectedIds([]);
    }, [debouncedQuery]);

    // Back / forward restores the whole view from the URL.
    useEffect(() => {
        const onPopState = () => {
            const view = readUrlView(tab, new URLSearchParams(window.location.search));
            setSearchQuery(view.search);
            setDebouncedQuery(view.search);
            setFilters(view.filters);
            setDateRangeState(view.dateRange);
            setCurrentPage(view.page);
            setSelectedIds([]);
        };
        window.addEventListener("popstate", onPopState);
        return () => window.removeEventListener("popstate", onPopState);
    }, [tab]);

    // Mirror the view into the URL without adding history entries (drawer params are kept).
    useEffect(() => {
        const current = window.location.search.replace(/^\?/, "");
        const target = new URLSearchParams(current);
        writeUrlView(target, { search: debouncedQuery, page: currentPage, filters, dateRange });
        if (target.toString() !== current) {
            window.history.replaceState(window.history.state, "", `${pathname}?${target.toString()}`);
        }
    }, [debouncedQuery, currentPage, filters, dateRange, pathname]);

    // ── Filters ─────────────────────────────────────────────────────────────
    const filterFields: BarcodeFilterField[] = useMemo(
        () => FILTER_DEFS[tab].map((def) => ({
            key: def.key,
            label: def.label,
            options: buildFilterOptions(def, rows, filters[def.key]),
        })),
        [tab, rows, filters],
    );

    const hasDateRange = Boolean(dateRange.from || dateRange.to);
    const activeFilterCount = Object.keys(filters).length + (hasDateRange ? 1 : 0);

    // A filter change re-shapes the visible rows: back to page 1, selection dropped,
    // so bulk actions never touch rows the user can no longer see.
    const resetView = useCallback(() => {
        setCurrentPage(1);
        setSelectedIds([]);
    }, []);

    const setFilter = useCallback((key: BarcodeFilterKey, value: string) => {
        setFilters((prev) => {
            const next = { ...prev };
            if (value) {
                next[key] = value;
            } else {
                delete next[key];
            }
            return next;
        });
        resetView();
    }, [resetView]);

    const setDateRange = useCallback((range: BarcodeDateRange) => {
        const from = parseDayKey(range.from);
        const to = parseDayKey(range.to);
        setDateRangeState(from && to && from > to ? { from: to, to: from } : { from, to });
        resetView();
    }, [resetView]);

    /** "Clear" resets the dropdowns, the date range and the search box. */
    const clearFilters = useCallback(() => {
        setFilters({});
        setDateRangeState({ from: null, to: null });
        setSearchQuery("");
        setDebouncedQuery("");
        resetView();
    }, [resetView]);

    // ── Data pipeline ───────────────────────────────────────────────────────
    const activeTabData = useMemo(() => {
        const query = debouncedQuery.trim().toLowerCase();
        const getSearchText = SEARCH_TEXT[tab];
        const getDate = DATE_OF[tab];
        const activeDefs = FILTER_DEFS[tab].filter((def) => filters[def.key]);

        const filtered = query || activeDefs.length > 0 || hasDateRange
            ? rows.filter((row) => (
                (!query || getSearchText(row).some((text) => text !== null && text.toLowerCase().includes(query)))
                && activeDefs.every((def) => def.getValue(row) === filters[def.key])
                && isWithinDayRange(getDate(row), dateRange)
            ))
            : rows;

        if (!sortKey || !sortDirection) {
            return filtered;
        }
        const direction = sortDirection === "asc" ? 1 : -1;
        return [...filtered].sort((a, b) => compareValues(a[sortKey], b[sortKey]) * direction);
    }, [rows, tab, debouncedQuery, filters, dateRange, hasDateRange, sortKey, sortDirection]);

    const totalPages = Math.max(1, Math.ceil(activeTabData.length / perPage));

    // Never strand the user past the last page (rows deleted, URL page too high).
    const safePage = Math.min(currentPage, totalPages);

    const paginatedData = useMemo(() => {
        const start = (safePage - 1) * perPage;
        return activeTabData.slice(start, start + perPage);
    }, [activeTabData, safePage, perPage]);

    // ── Sorting ─────────────────────────────────────────────────────────────
    const handleSort = useCallback((key: keyof BarcodesRecordMap[K] & string) => {
        if (sortKey !== key) {
            setSortKey(key);
            setSortDirection("asc");
            return;
        }
        if (sortDirection === "asc") {
            setSortDirection("desc");
            return;
        }
        setSortKey(null);
        setSortDirection(null);
    }, [sortKey, sortDirection]);

    // ── Selection ───────────────────────────────────────────────────────────
    const isAllSelected = activeTabData.length > 0 && selectedIds.length === activeTabData.length;

    const toggleSelection = useCallback((id: string | "ALL") => {
        if (id === "ALL") {
            setSelectedIds((prev) => (
                prev.length === activeTabData.length && activeTabData.length > 0
                    ? []
                    : activeTabData.map(getRowId)
            ));
            return;
        }
        setSelectedIds((prev) => (prev.includes(id) ? prev.filter((item) => item !== id) : [...prev, id]));
    }, [activeTabData]);

    const clearSelection = useCallback(() => setSelectedIds([]), []);

    // ── Record actions (History is read-only) ───────────────────────────────
    const canEdit = isEditableTab(tab);

    const canDelete = useCallback((barcode: Barcode) => canEdit && getDeleteError(barcode) === null, [canEdit]);
    /** Edit is offered on List / Generate only, and never for a Sold (final) barcode. */
    const canEditRecord = useCallback((barcode: Barcode) => canEdit && canEditBarcode(barcode), [canEdit]);
    const canEditLocation = useCallback((barcode: Barcode) => getEditError(barcode, "currentLocation") === null, []);

    const handleDelete = useCallback((ids: string[]) => {
        if (!canEdit || ids.length === 0) {
            return;
        }
        const result = useGlobalBarcodesStore.getState().deleteBarcodes(ids);
        setSelectedIds((prev) => prev.filter((id) => !result.applied.includes(id)));
        reportResult(result, (count) => (count === 1 ? "Barcode deleted successfully." : `Deleted ${count} barcodes.`));
    }, [canEdit]);

    const handleBulkDelete = useCallback(() => handleDelete(selectedIds), [handleDelete, selectedIds]);

    /** Edit drawer save. Returns true when at least one field changed. */
    const handleUpdate = useCallback((id: string, changes: BarcodeEditInput): boolean => {
        if (!canEdit) {
            return false;
        }
        const result = useGlobalBarcodesStore.getState().updateBarcode(id, changes, BARCODES_AUDIT_ACTOR);
        if (result.applied.length === 0 && result.rejected.length === 0) {
            toast.info("No changes to save.");
            return false;
        }
        reportResult(result, () => "Barcode updated successfully.");
        return result.applied.length > 0;
    }, [canEdit]);

    const handleMarkPrinted = useCallback((ids: string[]) => {
        if (ids.length === 0) {
            return;
        }
        const result = useGlobalBarcodesStore.getState().markPrinted(ids, BARCODES_AUDIT_ACTOR);
        reportResult(result, (count) => `Sent ${count} barcode(s) to the printer.`);
    }, []);

    // ── Drawer state (URL-driven) ───────────────────────────────────────────
    const drawerMode = toDrawerMode(command.activeDrawer);
    const activeId = command.activeId;

    /** Drawers always target a barcode id (History rows open with their `barcodeId`). */
    const activeBarcode = useMemo(
        () => (activeId ? barcodes.find((barcode) => barcode.id === activeId) ?? null : null),
        [barcodes, activeId],
    );
    const activeJourney = useMemo(() => (activeBarcode ? buildJourney(activeBarcode) : []), [activeBarcode]);

    const openDrawer = useCallback((mode: Exclude<BarcodesDrawerMode, "none">, barcodeId: string) => {
        if (mode === "edit-barcode") {
            const barcode = useGlobalBarcodesStore.getState().barcodes.find((item) => item.id === barcodeId);
            if (!barcode || !canEditRecord(barcode)) {
                return;
            }
        }
        startTransition(() => {
            command.openView("drawer", mode, barcodeId);
        });
    }, [command, canEditRecord]);

    const closeDrawer = useCallback(() => {
        startTransition(() => {
            command.closeView();
        });
    }, [command]);

    return {
        tab,
        isPending,

        // Data & search
        rows,
        activeTabData,
        paginatedData,
        searchQuery,
        setSearchQuery,

        // Filters & date range
        filters,
        filterFields,
        activeFilterCount,
        setFilter,
        dateRange,
        setDateRange,
        clearFilters,

        // Sorting
        sortKey,
        sortDirection,
        handleSort,

        // Selection
        selectedIds,
        toggleSelection,
        clearSelection,
        isAllSelected,

        // Pagination
        currentPage: safePage,
        setCurrentPage,
        perPage,
        setPerPage,
        totalPages,

        // Record actions
        canEdit,
        canDelete,
        canEditRecord,
        canEditLocation,
        handleDelete,
        handleBulkDelete,
        handleUpdate,
        handleMarkPrinted,

        // Drawer
        drawerMode,
        activeId,
        activeBarcode,
        activeJourney,
        openDrawer,
        closeDrawer,
    };
}

export type BarcodesManager<K extends BarcodesTabKey> = ReturnType<typeof useBarcodesManager<K>>;
