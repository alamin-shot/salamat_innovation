import { DateRangeValue } from "@/types/ui";

// LAYER 1: Barcodes section type definitions.
// A barcode is one tracked physical unit. Its journey is an append-only list of
// lifecycle events; its status is always the type of the latest event.

// ── Lifecycle ───────────────────────────────────────────────────────────────
export type BarcodeEventType = "Generated" | "Printed" | "Received" | "Transferred" | "Sold";

/** A barcode's status is the type of its latest lifecycle event. */
export type BarcodeStatus = BarcodeEventType;

export type BarcodeLocation =
    | "Warehouse A"
    | "Warehouse B"
    | "Jamuna Future Park"
    | "Bashundhara City"
    | "TEKZO Online Shop";

export type BarcodePartyRole = "Supplier" | "Customer" | "Employee";

/** Text-based today; `id` is filled once People / Employees come from the backend. */
export interface BarcodeParty<R extends BarcodePartyRole = BarcodePartyRole> {
    id: string | null;
    name: string;
    role: R;
}

export type BarcodeSupplier = BarcodeParty<"Supplier">;
export type BarcodeCustomer = BarcodeParty<"Customer">;
export type BarcodeEmployee = BarcodeParty<"Employee">;

/** Fields every lifecycle event carries. */
interface BarcodeEventBase {
    id: string;
    /** ISO 8601. Sortable and date-range filterable. */
    timestamp: string;
    /** The actor who performed the action. */
    createdBy: string;
    /** Where it happened. For a transfer this is the destination. */
    location: BarcodeLocation;
    /** PO- / INV- / ST- number when one exists. */
    reference: string | null;
    note: string;
}

export interface BarcodeGeneratedEvent extends BarcodeEventBase {
    type: "Generated";
}

export interface BarcodePrintedEvent extends BarcodeEventBase {
    type: "Printed";
}

export interface BarcodeReceivedEvent extends BarcodeEventBase {
    type: "Received";
    supplier: BarcodeSupplier;
    /** Purchase price per unit (the History "Pricing" column). */
    price: number | null;
}

export interface BarcodeTransferredEvent extends BarcodeEventBase {
    type: "Transferred";
    fromLocation: BarcodeLocation;
    /** Hand-to-hand: who gave the unit and who took it. */
    handedOverBy: BarcodeEmployee;
    receivedBy: BarcodeEmployee | null;
}

export interface BarcodeSoldEvent extends BarcodeEventBase {
    type: "Sold";
    customer: BarcodeCustomer;
    /** Sale price per unit (the History "Pricing" column). */
    price: number | null;
}

/** Each event type carries exactly the party data it needs. */
export type BarcodeEvent =
    | BarcodeGeneratedEvent
    | BarcodePrintedEvent
    | BarcodeReceivedEvent
    | BarcodeTransferredEvent
    | BarcodeSoldEvent;

// ── Field-level audit log (Edit drawer) ─────────────────────────────────────
export type BarcodeEditableField = "mrp" | "currentLocation";

/** One edited field, e.g. "MRP | Old: 500 -> New: 450 | By: Admin". */
export interface BarcodeFieldChange {
    id: string;
    /** ISO 8601. */
    timestamp: string;
    changedBy: string;
    field: BarcodeEditableField;
    /** Display text of the value before and after; null means it was empty. */
    oldValue: string | null;
    newValue: string | null;
}

// ── Barcode ─────────────────────────────────────────────────────────────────
export interface Barcode {
    id: string;
    serialNumber: string;
    /** Link to useGlobalProductsStore; null when the product is not in the catalogue. */
    productId: string | null;
    productName: string;
    variant: string;
    sku: string;
    image: string | null;
    mrp: number | null;
    /** Always equals the type of the last lifecycle event. */
    status: BarcodeStatus;
    currentLocation: BarcodeLocation;
    /** Set by the Received event. */
    supplier: BarcodeSupplier | null;
    /** Set by the Sold event. */
    customer: BarcodeCustomer | null;
    /** ISO 8601; equals the Generated event's timestamp. */
    createdAt: string;
    /** Equals the Generated event's actor ("Generated By"). */
    createdBy: string;
    /** ISO 8601 of the last edit; null when never edited. */
    updatedAt: string | null;
    updatedBy: string | null;
    /** Oldest -> newest. Never empty: the first entry is always Generated. */
    lifecycleEvents: BarcodeEvent[];
    /** Oldest -> newest field edits made through the Edit drawer. */
    auditLog: BarcodeFieldChange[];
}

/** One entry of the merged journey timeline (lifecycle events + field edits). */
export type BarcodeJourneyEntry =
    | { kind: "event"; id: string; timestamp: string; event: BarcodeEvent }
    | { kind: "change"; id: string; timestamp: string; change: BarcodeFieldChange };

/** History table row: one per lifecycle event. Derived, never stored. */
export interface BarcodeHistoryRow {
    /** `${barcodeId}:${eventId}` */
    id: string;
    barcodeId: string;
    serialNumber: string;
    productName: string;
    variant: string;
    image: string | null;
    mrp: number | null;
    eventType: BarcodeEventType;
    timestamp: string;
    createdBy: string;
    location: BarcodeLocation;
    /** Only for Transferred events. */
    fromLocation: BarcodeLocation | null;
    /** Only on Received rows; the UI shows "—" otherwise. */
    supplier: string | null;
    /** Only on Sold rows; the UI shows "—" otherwise. */
    customer: string | null;
    /** Purchase price on Received rows, sale price on Sold rows. */
    price: number | null;
    reference: string | null;
    event: BarcodeEvent;
}

// ── Manager ─────────────────────────────────────────────────────────────────
export type BarcodesTabKey = "list" | "generated" | "history";

export interface BarcodesRecordMap {
    list: Barcode;
    generated: Barcode;
    history: BarcodeHistoryRow;
}

export type BarcodesRow = BarcodesRecordMap[BarcodesTabKey];

export type BarcodesDrawerMode = "none" | "view-barcode" | "edit-barcode";

export type BarcodesSortDirection = "asc" | "desc" | null;

export type BarcodeFilterKey =
    | "status"
    | "eventType"
    | "location"
    | "supplier"
    | "customer"
    | "generatedBy";

/** Selected dropdown values; a missing key means "All". */
export type BarcodeFilterValues = Partial<Record<BarcodeFilterKey, string>>;

/** Inclusive calendar range as YYYY-MM-DD; null means open-ended. */
export type BarcodeDateRange = DateRangeValue;

export interface BarcodeFilterOption {
    label: string;
    value: string;
}

export interface BarcodeFilterField {
    key: BarcodeFilterKey;
    label: string;
    options: BarcodeFilterOption[];
}

// ── Store inputs & results ──────────────────────────────────────────────────
/** auto: SKU-YYYYMMDD-0001 sequence. manual: the user typed / scanned each serial. */
export type BarcodeSerialMode = "auto" | "manual";

export interface BarcodeGenerateItem {
    productId: string | null;
    productName: string;
    variant: string;
    sku: string;
    image: string | null;
    mrp: number | null;
    quantity: number;
    serialMode: BarcodeSerialMode;
    /** Required when serialMode is "manual"; its length must equal `quantity`. */
    manualSerials: string[];
}

/** A catalogue product + variant resolved for barcode generation. */
export interface BarcodeProductChoice {
    productId: string | null;
    productName: string;
    variant: string;
    sku: string;
    image: string | null;
    mrp: number | null;
}

/** One row of the Create Barcode queue, before it is generated. */
export interface BarcodeStagedItem extends BarcodeProductChoice {
    /** Queue row id (not a barcode id). */
    id: string;
    /** Raw text of the Retail Price input, parsed on Generate. */
    mrpText: string;
    /** In manual mode this always equals manualSerials.length. */
    quantity: number;
    serialMode: BarcodeSerialMode;
    manualSerials: string[];
}

/** Print page: a scanned serial that is not in the system yet. */
export interface BarcodeMissingScan {
    serialNumber: string;
}

export interface BarcodeRejection {
    /** Barcode id, serial number or product name, whichever identifies the input. */
    target: string;
    reason: string;
}

export interface BarcodeActionResult {
    applied: string[];
    rejected: BarcodeRejection[];
}

export interface BarcodeReceiveInput {
    supplier: BarcodeSupplier;
    location: BarcodeLocation;
    price: number | null;
    reference: string | null;
    note?: string;
}

export interface BarcodeTransferInput {
    toLocation: BarcodeLocation;
    handedOverBy: BarcodeEmployee;
    receivedBy: BarcodeEmployee | null;
    reference: string | null;
    note?: string;
}

export interface BarcodeSaleInput {
    customer: BarcodeCustomer;
    price: number | null;
    reference: string | null;
    note?: string;
}

/** Fields the Edit drawer may change. Each real change is written to the audit log. */
export type BarcodeEditInput = Partial<Pick<Barcode, BarcodeEditableField>>;

// ── Store contract ──────────────────────────────────────────────────────────
export interface BarcodesState {
    barcodes: Barcode[];

    /** Creates `quantity` barcodes per item, each with a Generated event. `applied` holds the new ids. */
    generateBarcodes: (items: BarcodeGenerateItem[], location: BarcodeLocation, actor: string) => BarcodeActionResult;
    /** Logs a Printed event. Only Generated / Printed barcodes can be printed; a reprint is logged again. */
    markPrinted: (ids: string[], actor: string) => BarcodeActionResult;

    /** Entry points for Purchases / Stock Transfer / Sales once they are wired. */
    recordReceived: (id: string, input: BarcodeReceiveInput, actor: string) => BarcodeActionResult;
    recordTransfer: (id: string, input: BarcodeTransferInput, actor: string) => BarcodeActionResult;
    recordSale: (id: string, input: BarcodeSaleInput, actor: string) => BarcodeActionResult;

    /** Edit drawer. Writes one audit-log entry per field that actually changed. */
    updateBarcode: (id: string, changes: BarcodeEditInput, actor: string) => BarcodeActionResult;
    /** Only Generated / Printed barcodes can be deleted. */
    deleteBarcodes: (ids: string[]) => BarcodeActionResult;
}
